// Writes src/app/exampleOutlines.generated.ts from the bundled example boards in src/examples/.
// Run with: npm run outlines
// Pass --stdout to print the generated module without writing it to disk.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import type { BoardOutline } from '../src/app/outline.ts'
import type { Board } from '../src/board/schema.ts'
import { parseBoard } from '../src/board/validate.ts'
import { withAppModules } from './lib/vite.ts'

const examplesDir = new URL('../src/examples/', import.meta.url)
const outFile = new URL('../src/app/exampleOutlines.generated.ts', import.meta.url)

async function generateOutlinesText(): Promise<string> {
  const files = readdirSync(examplesDir)
    .filter((f) => f.endsWith('.board.json'))
    .sort()

  const entries = await withAppModules(['/scripts/lib/outline.ts'], ([mod]) => {
    const { buildOutline } = mod as { buildOutline: (board: Board) => BoardOutline }
    const out: Record<string, BoardOutline> = {}
    for (const file of files) {
      const text = readFileSync(new URL(file, examplesDir), 'utf8')
      const parsed = parseBoard(text)
      if (!parsed.ok) {
        throw new Error(`Example board ${file} failed to parse: ${parsed.errors.map((e) => e.message).join('; ')}`)
      }
      out[file] = buildOutline(parsed.board)
    }
    return out
  })

  return [
    '// Generated by `npm run outlines` from src/examples/*.board.json. Do not edit by hand.',
    "import type { BoardOutline } from './outline'",
    '',
    `export const EXAMPLE_OUTLINES: Readonly<Record<string, BoardOutline>> = ${JSON.stringify(entries, null, 2)}`,
    '',
  ].join('\n')
}

const text = await generateOutlinesText()
if (process.argv.includes('--stdout')) {
  process.stdout.write(text)
} else {
  writeFileSync(outFile, text)
  console.log(`Wrote ${fileURLToPath(outFile)}`)
}
